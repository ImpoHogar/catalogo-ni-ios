function precioDe(p) {
  const v = p && PRECIOS[p.code];
  return typeof v === 'number' && v > 0 ? v : null;
}

// 1650 -> "₡1.650"
function colones(n) {
  return '₡' + Math.round(n).toString().replace(/\B(?=(\d{3})+(?!\d))/g, '.');
}

// Total en colones de lo que hay en el carrito (solo productos con precio).
function totalCarrito() {
  return Object.keys(qtyMap).reduce((s, id) => {
    const pr = precioDe(PRODUCTS_BY_ID[id]);
    return s + (pr ? pr * qtyMap[id] : 0);
  }, 0);
}
